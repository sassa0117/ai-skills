const updateStmt = db.prepare(
  `UPDATE CatalogItem SET transformBody = ? WHERE id = ?`
);

const items = db
  .prepare(
    `SELECT id, name FROM CatalogItem WHERE (source IS NULL OR source != 'mercari_only') AND ipShort LIKE '%プリキュア%'`
  )
  .all();

console.log(`プリキュア関連商品（駿河屋）: ${items.length} 件`);

let trueCount = 0;

const tx = db.transaction(() => {
  for (const item of items) {
    const name = item.name;
    let isTransform = false;

    for (const pat of NOISE_PATTERNS) {
      if (pat.test(name)) {
        isTransform = false;
        updateStmt.run(0, item.id);
        continue;
      }
    }

    for (const tn of TRANSFORM_NAMES) {
      if (name.includes(tn)) {
        isTransform = true;
        break;
      }
    }

    if (isTransform) {
      const noisyMatch = NOISE_PATTERNS.some((pat) => pat.test(name));
      if (noisyMatch) isTransform = false;
    }

    updateStmt.run(isTransform ? 1 : 0, item.id);
    if (isTransform) trueCount++;
  }
});

tx();

console.log(`transformBody = true にマーク: ${trueCount} 件`);

db.close();
